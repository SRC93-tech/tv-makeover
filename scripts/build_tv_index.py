#!/usr/bin/env python3
"""Regenerate tvs/INDEX.md from the header comments of every tvs/<folder>/debloat.txt.

Usage: python3 -I scripts/build_tv_index.py
The headers are free text written by different people, so the columns are best-effort: open the folder for
the full notes before acting on a row.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TVS = os.path.join(ROOT, 'tvs')
LAUNCHERS = ['com.google.android.apps.tv.launcherx', 'com.google.android.tvlauncher', 'com.google.android.leanbacklauncher',
             'com.mitv.tvhome', 'com.tcl.cyberui', 'com.zeasn.whale.saas', 'com.amazon.tv.launcher', 'com.android.tv.launcher']
CHIP = re.compile(r'\b(MediaTek[ -]?\w*|Amlogic[ -]?\w*|Realtek[ -]?\w*|MStar[ -]?\w*|Rockchip[ -]?\w*|Allwinner[ -]?\w*|'
                  r'HiSilicon[ -]?\w*|Novatek[ -]?\w*|Qualcomm[ -]?\w*|Tegra[ -]?\w*|MT\d{4}\w*|RTD\d{4}\w*|S9\d\dX\w*)', re.I)


def header(text):
    lines = []
    for line in text.splitlines():
        if not line.startswith('#'):
            break
        body = line[1:].strip()
        if not body and lines:
            break
        if body:
            lines.append(body)
    return lines


def row(folder):
    text = open(os.path.join(TVS, folder, 'debloat.txt'), encoding='utf-8', errors='replace').read()
    head = header(text)
    first = ' '.join(head[:2])
    device = re.split(r'\s*\(|,', head[0])[0] if head else folder
    joined = ' '.join(head)
    m = re.search(r'(Google TV|Android TV|Android|Fire OS)\s*(\d+(?:\.\d+)?)', joined)
    android = f'{m.group(1)} {m.group(2)}' if m else ''
    chip = CHIP.search(joined)
    stock = ''
    for line in text.splitlines()[:80]:
        if re.search(r'stock (launcher|home)', line, re.I):
            stock = next((p for p in LAUNCHERS if p in line), '')
            if stock:
                break
    if not stock:
        stock = next((p for p in LAUNCHERS if p in text), '')
    profile = os.path.join(TVS, folder, 'profile.json')
    has_profile = os.path.exists(profile)
    if has_profile:
        stock = json.load(open(profile, encoding='utf-8')).get('stock_launcher', stock)
    return device.strip(), android, chip.group(0) if chip else '', stock, has_profile, first


def main():
    folders = sorted(d for d in os.listdir(TVS) if os.path.isfile(os.path.join(TVS, d, 'debloat.txt')))
    out = ['# TV index', '',
           f'{len(folders)} tested TVs and boxes. Generated by `scripts/build_tv_index.py` from each folder\'s',
           '`debloat.txt` header; the columns are best-effort, the folder has the full notes. "profile" marks folders',
           'with a `profile.json` that `scripts/apply-template.sh --tv <folder>` can use directly.',
           'Find the closest match to a TV with `scripts/find-tv-profile.sh <brand model chip ...>`.', '',
           '| Folder | Device | Android | Chip | Stock home | |', '|---|---|---|---|---|---|']
    for f in folders:
        device, android, chip, stock, prof, _ = row(f)
        out.append(f'| [{f}]({f}/) | {device[:60]} | {android} | {chip} | `{stock}` | {"profile" if prof else ""} |'
                   .replace('``', ''))
    open(os.path.join(TVS, 'INDEX.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print(f'tvs/INDEX.md: {len(folders)} rows')


if __name__ == '__main__':
    main()
